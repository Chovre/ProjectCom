package com.ledgerline.controller;

import com.ledgerline.dto.AuditLogResponse;
import com.ledgerline.entity.User;
import com.ledgerline.service.AuditService;
import com.ledgerline.service.UserService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import lombok.RequiredArgsConstructor;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Sort;
import org.springframework.data.web.PageableDefault;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/api/audit")
@RequiredArgsConstructor
@Tag(name = "Audit", description = "Endpoints for user audit trail")
public class AuditController {

    private final AuditService auditService;
    private final UserService userService;

    @GetMapping("/my")
    @Operation(summary = "Get user's audit logs", description = "Returns append-only audit trail logs generated by the current authenticated user")
    public ResponseEntity<Page<AuditLogResponse>> getMyAuditLogs(
            @PageableDefault(size = 10, sort = "createdAt", direction = Sort.Direction.DESC) Pageable pageable) {
        User user = userService.getCurrentUser();
        Page<AuditLogResponse> logs = auditService.getMyAuditLogs(user.getId(), pageable);
        return ResponseEntity.ok(logs);
    }
}

